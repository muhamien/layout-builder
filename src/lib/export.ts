function elementToHTML(el: WireframeElement): string {
  const s = ELEMENT_STYLE[el.type] ?? ELEMENT_STYLE.main
  const style = [
    `position:absolute`,
    `left:${el.x}px`,
    `top:${el.y}px`,
    `width:${el.width}px`,
    `height:${el.height}px`,
    `background:${s.bg}`,
    `border:1.5px solid ${s.border}`,
    `border-radius:4px`,
    `color:${s.color}`,
    `display:flex`,
    `align-items:center`,
    `justify-content:center`,
    `flex-direction:column`,
    `gap:4px`,
    `font-family:'Sora',sans-serif`,
    `font-size:${Math.min(13, Math.max(9, el.height * 0.16))}px`,
    `font-weight:500`,
    `text-align:center`,
    `padding:0 8px`,
    `box-sizing:border-box`,
    `overflow:hidden`,
  ].join(';')

  const tag = s.tag === 'hr' ? 'div' : s.tag
  const sizeLabel = `<span style="font-size:9px;opacity:0.4;font-family:'Space Mono',monospace;margin-top:2px">${el.width}×${el.height}</span>`
  const content = `<span>${el.label}</span>${el.height > 48 ? sizeLabel : ''}`

  return `    <${tag} data-type="${el.type}" aria-label="${el.label}" style="${style}">\n      ${content}\n    </${tag}>`
}

